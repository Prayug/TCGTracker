import type { CardPrediction, PredictionCategory } from '../types';

type DemoSeed = {
  id: number;
  cardId: string;
  cardName: string;
  setId: string;
  setName: string;
  cardNumber: string;
  rarity: string;
  currentPrice: number;
  expected90dReturn: number;
  confidenceScore: number;
  riskScore: number;
  category: PredictionCategory;
  suggestedAction: string;
};

function buildPrediction(seed: DemoSeed): CardPrediction {
  const { currentPrice: p, expected90dReturn: r90 } = seed;
  const mid90 = +(p * (1 + r90)).toFixed(2);
  const mid30 = +(p * (1 + r90 * 0.45)).toFixed(2);
  const mid7 = +(p * (1 + r90 * 0.12)).toFixed(2);
  return {
    id: seed.id,
    cardId: seed.cardId,
    cardName: seed.cardName,
    setId: seed.setId,
    setName: seed.setName,
    cardNumber: seed.cardNumber,
    rarity: seed.rarity,
    imageSmall: `https://images.pokemontcg.io/${seed.setId}/${seed.cardNumber}.png`,
    imageLarge: `https://images.pokemontcg.io/${seed.setId}/${seed.cardNumber}_hires.png`,
    currentPrice: seed.currentPrice,
    predicted7dLow: +(mid7 * 0.92).toFixed(2),
    predicted7dMid: mid7,
    predicted7dHigh: +(mid7 * 1.08).toFixed(2),
    predicted30dLow: +(mid30 * 0.88).toFixed(2),
    predicted30dMid: mid30,
    predicted30dHigh: +(mid30 * 1.12).toFixed(2),
    predicted90dLow: +(mid90 * 0.82).toFixed(2),
    predicted90dMid: mid90,
    predicted90dHigh: +(mid90 * 1.18).toFixed(2),
    expected7dReturn: +(r90 * 0.12).toFixed(4),
    expected30dReturn: +(r90 * 0.45).toFixed(4),
    expected90dReturn: r90,
    confidenceScore: seed.confidenceScore,
    riskScore: seed.riskScore,
    category: seed.category,
    suggestedAction: seed.suggestedAction,
    explanation: '',
    riskFactors: 'Low identifiable risk factors.',
    externalSignals: '[]',
    modelVersion: 'demo',
  };
}

